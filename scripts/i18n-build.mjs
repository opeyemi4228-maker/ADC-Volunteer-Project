/**
 * Builds lib/i18n/{ha,yo,ig,pcm}.js from lib/i18n/translations.tsv.
 * Edit the TSV (one row per English string, tab-separated), then run
 *   node scripts/i18n-build.mjs
 * All translations are drafts until a native speaker has reviewed them.
 */
import fs from "node:fs";

const rows = fs.readFileSync("lib/i18n/translations.tsv", "utf8").split("\n").filter(Boolean);
const [header, ...data] = rows.map((r) => r.split("\t"));
for (const [col, lang] of header.entries()) {
  if (lang === "en") continue;
  const dict = {};
  for (const r of data) if (r[col] && r[col] !== r[0]) dict[r[0]] = r[col];
  const body = Object.entries(dict).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  fs.writeFileSync(
    `lib/i18n/${lang}.js`,
    `/* Generated by scripts/i18n-build.mjs from translations.tsv. Draft: needs native-speaker review. */\nexport default {\n${body}\n};\n`,
  );
  console.log(lang, Object.keys(dict).length);
}
